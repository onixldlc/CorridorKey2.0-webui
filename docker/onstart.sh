#!/bin/bash
# Starts ck-web when the image ENTRYPOINT will not run.
#
# Rented-box consoles (Vast.ai and friends) offer a launch mode that replaces
# the image entrypoint with their own shell server, so picking "SSH" means the
# server never starts. Point that console's on-start script at this file and
# both happen: their sshd is PID 1, ck-web runs beside it.
#
# Nothing here is specific to one provider. It is a wrapper around
# entrypoint.sh, not a second copy of it.
set -u

LOG="${CKWEB_LOG:-/var/log/ck-web.log}"
touch "$LOG"

# The console's environment table lands in /etc/environment, not in this
# shell, so the ENV defaults baked into the image are not visible here.
set -a
[ -f /etc/environment ] && . /etc/environment
set +a

: "${CKWEB_ADDR:=:8080}"
: "${CKWEB_ROOT:=/opt/corridorkey}"
: "${CKWEB_CLIPS:=/data/ClipsForInference}"
: "${CKWEB_PYTHON:=/opt/venv/bin/python}"
: "${CKWEB_MODE:=auto}"
: "${CKWEB_TOKEN:=auto}"
export CKWEB_ADDR CKWEB_ROOT CKWEB_CLIPS CKWEB_PYTHON CKWEB_MODE CKWEB_TOKEN
export OPENCV_IO_ENABLE_OPENEXR=1

if pgrep -x ck-web >/dev/null 2>&1; then
    echo "onstart: ck-web already running, leaving it alone" >> "$LOG"
    exit 0
fi

nohup /usr/local/bin/entrypoint.sh >> "$LOG" 2>&1 &

# The token is generated by the server and only ever printed, so wait for the
# line that carries it rather than inventing one here.
for _ in $(seq 1 90); do
    grep -q 'http://' "$LOG" && break
    sleep 1
done

URL="$(grep -o 'http://[^[:space:]]*' "$LOG" | tail -1)"
TOKEN="$(printf '%s' "$URL" | sed -n 's/.*[?&]t=\([^&]*\).*/\1/p')"
printf '%s\n' "$URL" > /root/ck-web-url.txt

if [ -z "$TOKEN" ]; then
    echo "onstart: no token in the log after 90s — see $LOG" >> "$LOG"
    exit 1
fi

# The link the server prints says localhost, because that is all it can know.
# A rented box publishes 8080 on some other port, so the reachable URL is
# assembled here and shown at every login.
mkdir -p /etc/profile.d
cat > /etc/profile.d/ck-web.sh <<PROFILE
ck_url() {
    if [ -n "\${VAST_TCP_PORT_8080:-}" ] && [ -n "\${PUBLIC_IPADDR:-}" ]; then
        echo "http://\${PUBLIC_IPADDR}:\${VAST_TCP_PORT_8080}/?t=${TOKEN}"
    else
        echo "http://localhost:8080/?t=${TOKEN}"
    fi
}
echo
echo "ck-web   \$(ck_url)"
echo "         tunnel: ssh -L 8080:localhost:8080 <this box>"
echo "         log:    tail -f ${LOG}"
echo
PROFILE
chmod +x /etc/profile.d/ck-web.sh

echo "onstart: ck-web up, token issued" >> "$LOG"
